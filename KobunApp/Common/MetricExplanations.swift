import Foundation

/// 画面に出る数値の定義文。
///
/// 正答率や習熟度は定義が分からないと解釈できず、誤解したまま一喜一憂させてしまう。
/// 説明をヘルプやREADMEに置かず、指標のすぐ隣の「i」から開けるようにしている。
/// 文言を1か所に集めているのは、ホームと結果画面で違う説明が出るのを防ぐため。
enum MetricExplanations {
    static let masteryStages: String = {
        let lines = LearningStatus.allCases.map { "\($0.displayName): \($0.criteria)" }
        return ([
            "学習の進み具合を4段階で表します。段階は解答の記録から自動で決まります。",
            ""
        ] + lines).joined(separator: "\n")
    }()

    static let streak = """
    続けて学習した日数です。当日まだ学習していない場合も、前日までの記録で数えます。
    朝アプリを開いた時点で0日と表示されると、続ける手がかりにならないためです。
    """

    static let accuracy = """
    解いた問題に対する正解の割合です。期間で見るときは解答数で重みを付けて平均します。
    日ごとの正答率をそのまま平均すると、1問しか解かなかった日が大きく効いてしまうためです。
    """

    static let dueCount = """
    復習の期限が来ている項目の数です。間違えた項目は当日中に、正解した項目は
    1日→3日→7日→14日→30日と間隔を広げながら戻ってきます。
    """

    static let grammarMastery = """
    文法項目の習熟度は、その項目に紐づく問題の成績から決まります。
    1問でも要復習があれば「要復習」、すべてが「覚えた」に達したときだけ「覚えた」になります。
    解ける問題が残っているうちに「覚えた」と表示しないための決め方です。
    """

}
